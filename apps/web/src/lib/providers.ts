export function getProviderMeta(providerName: string) {
  const norm = (providerName || '').toLowerCase().trim();
  const found = PROVIDER_CATALOG.find((p) => p.id === norm || (p.aliases && p.aliases.includes(norm)));

  if (found) {
    if (norm.includes('openai')) {
      return {
        label: found.name,
        badgeColor: 'success',
        accentBg: 'bg-emerald-50',
        accentBorder: 'border-emerald-200',
        accentText: 'text-emerald-700',
        symbol: 'OA',
        tag: found.tag,
        category: found.category,
      };
    }
    if (norm.includes('claude') || norm.includes('anthropic')) {
      return {
        label: found.name,
        badgeColor: 'warning',
        accentBg: 'bg-amber-50',
        accentBorder: 'border-amber-200',
        accentText: 'text-amber-700',
        symbol: 'CL',
        tag: found.tag,
        category: found.category,
      };
    }
    if (norm.includes('gemini') || norm.includes('google')) {
      return {
        label: found.name,
        badgeColor: 'blue',
        accentBg: 'bg-blue-50',
        accentBorder: 'border-blue-200',
        accentText: 'text-blue-700',
        symbol: 'GM',
        tag: found.tag,
        category: found.category,
      };
    }
    if (norm.includes('groq')) {
      return {
        label: found.name,
        badgeColor: 'warning',
        accentBg: 'bg-orange-50',
        accentBorder: 'border-orange-200',
        accentText: 'text-orange-700',
        symbol: 'GQ',
        tag: found.tag,
        category: found.category,
      };
    }
    if (norm.includes('deepseek')) {
      return {
        label: found.name,
        badgeColor: 'cyan',
        accentBg: 'bg-cyan-50',
        accentBorder: 'border-cyan-200',
        accentText: 'text-cyan-700',
        symbol: 'DS',
        tag: found.tag,
        category: found.category,
      };
    }
    if (norm.includes('cerebras')) {
      return {
        label: found.name,
        badgeColor: 'indigo',
        accentBg: 'bg-indigo-50',
        accentBorder: 'border-indigo-200',
        accentText: 'text-indigo-700',
        symbol: 'CB',
        tag: found.tag,
        category: found.category,
      };
    }
    if (norm.includes('together')) {
      return {
        label: found.name,
        badgeColor: 'blue',
        accentBg: 'bg-sky-50',
        accentBorder: 'border-sky-200',
        accentText: 'text-sky-700',
        symbol: 'TG',
        tag: found.tag,
        category: found.category,
      };
    }
    if (norm.includes('fireworks')) {
      return {
        label: found.name,
        badgeColor: 'warning',
        accentBg: 'bg-rose-50',
        accentBorder: 'border-rose-200',
        accentText: 'text-rose-700',
        symbol: 'FW',
        tag: found.tag,
        category: found.category,
      };
    }
    if (norm.includes('openrouter')) {
      return {
        label: found.name,
        badgeColor: 'indigo',
        accentBg: 'bg-violet-50',
        accentBorder: 'border-violet-200',
        accentText: 'text-violet-700',
        symbol: 'OR',
        tag: found.tag,
        category: found.category,
      };
    }
    if (found.category === 'local') {
      return {
        label: found.name,
        badgeColor: 'cyan',
        accentBg: 'bg-teal-50',
        accentBorder: 'border-teal-200',
        accentText: 'text-teal-700',
        symbol: found.name.slice(0, 2).toUpperCase(),
        tag: found.tag,
        category: found.category,
      };
    }
    if (found.category === 'enterprise') {
      return {
        label: found.name,
        badgeColor: 'blue',
        accentBg: 'bg-blue-50',
        accentBorder: 'border-blue-200',
        accentText: 'text-blue-700',
        symbol: found.name.slice(0, 2).toUpperCase(),
        tag: found.tag,
        category: found.category,
      };
    }
    return {
      label: found.name,
      badgeColor: 'purple',
      accentBg: 'bg-purple-50',
      accentBorder: 'border-purple-200',
      accentText: 'text-purple-700',
      symbol: found.name.slice(0, 2).toUpperCase(),
      tag: found.tag,
      category: found.category,
    };
  }

  // Custom provider fallback
  return {
    label: providerName.charAt(0).toUpperCase() + providerName.slice(1),
    badgeColor: 'purple',
    accentBg: 'bg-purple-50',
    accentBorder: 'border-purple-200',
    accentText: 'text-purple-700',
    symbol: providerName.slice(0, 2).toUpperCase() || 'AI',
    tag: 'Custom API',
    category: 'custom',
  };
}
